export function iconSvg(name, size = 15) {
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2"`
    + ` stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
}

export function icon(name, size) {
  const span = document.createElement('span');
  span.className = 'ico';
  span.innerHTML = iconSvg(name, size);
  return span;
}

// Static markup marks icon slots with data-icon="name".
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) el.replaceChildren(icon(el.dataset.icon, +el.dataset.size || undefined));
}
